-- Admin decisions about who takes part in a cycle, overriding the Users page:
-- included = true  -> added by hand (e.g. a Manager who is not normally appraised)
-- included = false -> removed by hand; not added back automatically
CREATE TABLE cycle_membership (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id bigint NOT NULL REFERENCES cycle(id),
    user_id bigint NOT NULL REFERENCES app_user(id),
    included boolean NOT NULL,
    CONSTRAINT cycle_membership_cycle_user_key UNIQUE (cycle_id, user_id)
);
