-- Initial schema for the performance appraisal app.
-- Live (editable) question bank: team, level, category, question, scoring_settings, rating_band, scale_label, pick_list_item.
-- Frozen per-cycle copies: cycle_level, cycle_category, cycle_question, cycle_rating_band (taken when a cycle opens).
-- Reviews: appraisal (employee x cycle), review (reviewer x role), answer, achievement, goal.

CREATE TABLE achievement (
    sort_order integer NOT NULL,
    verified boolean NOT NULL,
    appraisal_id bigint NOT NULL,
    id bigint NOT NULL,
    business_impact character varying(200),
    situation character varying(200),
    text character varying(1000) NOT NULL
);

ALTER TABLE achievement ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME achievement_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

